import { createClientFromRequest } from 'npm:@base44/sdk@0.8.25';

Deno.serve(async (req) => {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });

    const [bookmarks, highlights, notes] = await Promise.all([
      base44.entities.Bookmark.list('-created_date', 200),
      base44.entities.UserHighlight.list('-created_date', 200),
      base44.entities.UserNote.list('-created_date', 200),
    ]);

    const lines = [];
    lines.push(`VERITAS BIBLE — PERSONAL LIBRARY EXPORT`);
    lines.push(`Exported: ${new Date().toUTCString()}`);
    lines.push(`User: ${user.full_name || user.email}`);
    lines.push('='.repeat(60));
    lines.push('');

    // Bookmarks
    lines.push('BOOKMARKS');
    lines.push('-'.repeat(40));
    if (bookmarks.length === 0) {
      lines.push('  (none)');
    } else {
      bookmarks.forEach((bm, i) => {
        lines.push(`  ${i + 1}. ${bm.verse_ref}${bm.label ? ' — ' + bm.label : ''} [${bm.translation || ''}]`);
      });
    }
    lines.push('');

    // Highlights
    lines.push('HIGHLIGHTS');
    lines.push('-'.repeat(40));
    if (highlights.length === 0) {
      lines.push('  (none)');
    } else {
      highlights.forEach((hl, i) => {
        lines.push(`  ${i + 1}. ${hl.verse_ref} — ${hl.color} [${hl.translation || ''}]`);
      });
    }
    lines.push('');

    // Notes
    lines.push('PERSONAL NOTES');
    lines.push('-'.repeat(40));
    if (notes.length === 0) {
      lines.push('  (none)');
    } else {
      notes.forEach((n, i) => {
        const date = n.created_date ? new Date(n.created_date).toLocaleDateString('en-US') : '';
        lines.push(`  ${i + 1}. [${n.verse_ref}]${date ? ' (' + date + ')' : ''}`);
        lines.push(`     ${n.note_text}`);
        lines.push('');
      });
    }

    lines.push('='.repeat(60));
    lines.push('Generated by Veritas Bible App');

    const content = lines.join('\n');

    return new Response(content, {
      status: 200,
      headers: {
        'Content-Type': 'text/plain; charset=utf-8',
        'Content-Disposition': `attachment; filename="veritas-library-${new Date().toISOString().slice(0, 10)}.txt"`,
      },
    });
  } catch (error) {
    return Response.json({ error: error.message }, { status: 500 });
  }
});